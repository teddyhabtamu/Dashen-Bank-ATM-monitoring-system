-- Quarantine non-real transaction data.
--
-- Why: simulators/txn_engine.py writes invented money movements into the same
-- atm_transactions table the portal reads, and the only thing separating them
-- from real data was a yellow banner. A banner is a label, not a control: one
-- screenshot, one CSV export or one new query later, simulated withdrawals are
-- being used to decide cash replenishment.
--
-- So enforcement moves into the database. atm_transactions_visible exposes only
-- sources an admin has marked trusted, and every read path in the portal goes
-- through it (enforced by tests/test_txn_sources.py, which fails if any query
-- reaches for the base table).
--
-- Deliberately an ALLOWLIST, not a blocklist of known fakes:
--   * an unrecognised source is invisible until someone trusts it, so a new
--     generator cannot leak by default;
--   * ISO8583_REAL is generated by scripts/fake_iso8583_switch.py and is
--     therefore NOT trusted, despite its reassuring name.
--
-- Safe to run repeatedly: IF NOT EXISTS / OR REPLACE, no data rewrite, no lock
-- on atm_transactions. Takes a backup first per docs/backup-and-restore.md.
--
--   docker exec -i zabbix-db psql -U zabbix -d zabbix < scripts/migrate_txn_sources.sql

CREATE TABLE IF NOT EXISTS txn_source_policy (
    source       character varying(20) PRIMARY KEY,
    label        character varying(60) NOT NULL,
    trusted      boolean NOT NULL DEFAULT false,
    enabled      boolean NOT NULL DEFAULT false,
    note         text
);

COMMENT ON TABLE txn_source_policy IS
  'Which transaction producers the portal may show. trusted = produces real bank data. enabled = visible right now. Non-trusted sources are only ever visible if an operator deliberately enables them for a demo (scripts/set_txn_sources.py), which is audited.';

INSERT INTO txn_source_policy (source, label, trusted, enabled, note) VALUES
    ('EJ',            'EJ journal (real ATM)',            true,  true,
     'Parsed from the ATM electronic journal. System of record for what the terminal did.'),
    ('ISO8583',       'ATM switch (ISO 8583)',            true,  true,
     'camel/iso8583_gateway.py. System of record for what the bank authorised.'),
    ('SIMULATOR',     'Transaction simulator',            false, false,
     'simulators/txn_engine.py invents transactions. Never a basis for a cash decision.'),
    ('ISO8583_SIM',   'Switch simulator',                 false, false,
     'scripts/fake_iso8583_switch.py --sim output.'),
    ('ISO8583_REAL',  'Switch test generator',            false, false,
     'scripts/fake_iso8583_switch.py default output. Fabricated despite the name - trusted stays false on purpose.')
ON CONFLICT (source) DO NOTHING;

-- Re-running this file must NOT reset an operator's choices. The seed above is
-- ON CONFLICT DO NOTHING, so it only ever inserts a source it has never seen;
-- existing rows are left exactly as scripts/set_txn_sources.py set them. That
-- matters because report-portal/audit.py runs this same DDL at every container
-- start - an UPDATE here would revert a demo toggle on the next restart, which
-- would make the audit log a lie.

CREATE OR REPLACE VIEW atm_transactions_visible AS
    SELECT t.*
      FROM atm_transactions t
     WHERE t.source IN (SELECT p.source FROM txn_source_policy p WHERE p.enabled);

COMMENT ON VIEW atm_transactions_visible IS
  'Every portal read of transaction data goes through this view, so the simulator cannot leak into a KPI, a CSV or a cash forecast by being forgotten in one query.';

-- Confirm before moving on: the view must be empty of simulated money while the
-- base table still holds it, i.e. the data is hidden, not deleted.
SELECT p.source,
       p.label,
       p.enabled,
       (SELECT count(*) FROM atm_transactions t WHERE t.source = p.source) AS rows_present,
       (SELECT count(*) FROM atm_transactions_visible v WHERE v.source = p.source) AS rows_visible
  FROM txn_source_policy p
 ORDER BY p.enabled DESC, p.source;
